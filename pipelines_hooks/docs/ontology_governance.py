"""ontology-governance: every tracked ontology file carries the authority's verdict for each required rule class.

Declared in ``.config/ontology-governance.json`` (ontology roots, supported RDF formats and the
generated authority artifact).  The authority artifact (``ontology-authority/1``) is generated by
the engine that owns ontology policy: it names the engine-owned rule ids, binds each rule to one of
the five required classes (``syntax``, ``namespace``, ``duplicate-identity``, ``shape``,
``vocabulary``) and carries, per ontology file, the source digest it judged and one verdict per
rule with a provenance of ``generated-check`` or ``served-verdict``.  This hook is a Python-only
reader: it recreates no ontology policy and makes no network call.  It evaluates the staged Git
snapshot, so an unstaged repair never hides a staged defect.

Exit 1: a verdict failed (rule, file and line are printed).  Exit 2 (``CannotRun``): no
declaration, missing or stale authority, an unsupported format, a rule class without evidence, or an
ontology file the authority never judged.  A parser success alone is never a pass.
"""

from __future__ import annotations

import argparse
import sys
from dataclasses import dataclass, field
from pathlib import Path, PurePosixPath

from pipelines_hooks.core.errors import CannotRun
from pipelines_hooks.core.gitenv import repo_root
from pipelines_hooks.core.tracked import tracked_paths
from pipelines_hooks.docs.gate_io import Result, finish, load_json, require, sha, strict_keys

GATE = "ontology-governance"
DECLARATION = ".config/ontology-governance.json"
FORMAT = "ontology-authority/1"
RULE_CLASSES = ("syntax", "namespace", "duplicate-identity", "shape", "vocabulary")
PROVENANCE = {"generated-check", "served-verdict"}
FORMATS = {".ttl": "turtle", ".owl": "rdf-xml", ".rdf": "rdf-xml", ".nt": "n-triples", ".jsonld": "json-ld"}


@dataclass(frozen=True)
class Verdict:
    rule: str
    status: str
    line: int
    message: str
    provenance: str


@dataclass(frozen=True)
class OntologyFile:
    path: str
    rdf_format: str
    digest: str
    verdicts: tuple[Verdict, ...]


@dataclass
class OntologyInputProfile:
    """Tracked ontology roots, supported formats and engine-owned rules, bound to authority and source digests."""

    roots: tuple[str, ...]
    formats: dict[str, str]
    authority: str
    authority_digest: str
    authority_owner: str
    rules: dict[str, str]
    files: list[OntologyFile] = field(default_factory=list)


def _verdict(path: str, raw: object, rules: dict[str, str]) -> Verdict:
    data = strict_keys(
        GATE,
        f"{path} verdict",
        raw,
        {"rule", "status", "line", "message", "provenance"},
        {"rule", "status", "provenance"},
    )
    if data["rule"] not in rules:
        raise CannotRun(f"{GATE}: {path} carries a verdict for rule {data['rule']!r} the authority does not publish")
    if data["status"] not in {"pass", "fail"}:
        raise CannotRun(f"{GATE}: {path} rule {data['rule']} has unknown status {data['status']!r}")
    if data["provenance"] not in PROVENANCE:
        raise CannotRun(f"{GATE}: {path} rule {data['rule']} has unknown provenance {data['provenance']!r}")
    return Verdict(
        data["rule"], data["status"], int(data.get("line", 1)), str(data.get("message", "")), data["provenance"]
    )


def _discover(root: Path, roots: tuple[str, ...]) -> list[str]:
    found = []
    for path in tracked_paths(root):
        pure = PurePosixPath(path)
        if any(pure.is_relative_to(base) for base in roots) and pure.suffix in {
            *FORMATS,
            ".n3",
            ".trig",
            ".nq",
            ".trix",
        }:
            found.append(path)
    return sorted(found)


def load_profile(root: Path) -> OntologyInputProfile:
    decl, _ = load_json(GATE, root, DECLARATION)
    decl = strict_keys(
        GATE,
        DECLARATION,
        decl,
        {"schema", "roots", "formats", "authority"},
        {"schema", "roots", "formats", "authority"},
    )
    if decl["schema"] != 1:
        raise CannotRun(f"{GATE}: unsupported declaration schema")
    roots = tuple(decl["roots"])
    if not roots or not all(isinstance(r, str) and r for r in roots):
        raise CannotRun(f"{GATE}: {DECLARATION} declares no ontology roots")
    formats = dict(decl["formats"])
    if not formats or not set(formats) <= set(FORMATS):
        raise CannotRun(f"{GATE}: {DECLARATION} names an unsupported RDF format {sorted(set(formats) - set(FORMATS))}")
    data, raw = load_json(GATE, root, decl["authority"])
    data = strict_keys(
        GATE,
        decl["authority"],
        data,
        {"format", "authority", "rules", "files"},
        {"format", "authority", "rules", "files"},
    )
    if data["format"] != FORMAT:
        raise CannotRun(f"{GATE}: unsupported authority format {data['format']!r}")
    rules: dict[str, str] = {}
    for rule in data["rules"]:
        rule = strict_keys(GATE, "authority rule", rule, {"id", "class"}, {"id", "class"})
        if rule["class"] not in RULE_CLASSES:
            raise CannotRun(f"{GATE}: authority rule {rule['id']} has unknown class {rule['class']!r}")
        rules[rule["id"]] = rule["class"]
    missing_classes = sorted(set(RULE_CLASSES) - set(rules.values()))
    if missing_classes:
        raise CannotRun(f"{GATE}: the authority publishes no rule for required classes {missing_classes}")
    profile = OntologyInputProfile(roots, formats, decl["authority"], sha(raw), str(data["authority"]), rules)
    for path in _discover(root, roots):
        suffix = PurePosixPath(path).suffix
        if suffix not in formats:
            raise CannotRun(f"{GATE}: {path} has an unsupported RDF format {suffix!r}")
        entry = data["files"].get(path)
        if entry is None:
            raise CannotRun(f"{GATE}: {path} was never judged by the authority")
        entry = strict_keys(GATE, path, entry, {"sha", "verdicts"}, {"sha", "verdicts"})
        blob = require(GATE, root, path)
        if entry["sha"] != sha(blob):
            raise CannotRun(f"{GATE}: stale authority verdicts for {path}")
        verdicts = tuple(_verdict(path, v, rules) for v in entry["verdicts"])
        covered = {rules[v.rule] for v in verdicts}
        if covered != set(RULE_CLASSES):
            raise CannotRun(f"{GATE}: {path} lacks evidence for rule classes {sorted(set(RULE_CLASSES) - covered)}")
        profile.files.append(OntologyFile(path, formats[suffix], sha(blob), verdicts))
    stray = sorted(set(data["files"]) - {f.path for f in profile.files})
    if stray:
        raise CannotRun(f"{GATE}: the authority judged files that are not staged ontology files: {stray}")
    if not profile.files:
        raise CannotRun(f"{GATE}: no staged ontology file under {list(roots)}; incomplete scope")
    return profile


def check(root: Path) -> Result:
    profile = load_profile(root)
    result = Result()
    result.lines.append(
        f"authority owner={profile.authority_owner} path={profile.authority} digest={profile.authority_digest} "
        f"rules={sorted(profile.rules)}"
    )
    for item in profile.files:
        for verdict in item.verdicts:
            if verdict.status == "fail":
                result.findings.append(
                    f"{item.path}:{verdict.line}: {verdict.rule} ({profile.rules[verdict.rule]}): {verdict.message}"
                )
        by_class: dict[str, list[str]] = {}
        for verdict in item.verdicts:
            by_class.setdefault(profile.rules[verdict.rule], []).append(
                f"{verdict.rule}={verdict.status}/{verdict.provenance}"
            )
        result.lines.append(
            f"file path={item.path} format={item.rdf_format} input-digest={item.digest} "
            + " ".join(f"{c}=[{','.join(by_class[c])}]" for c in RULE_CLASSES)
        )
    return result


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(prog=GATE, description=__doc__)
    parser.add_argument("--root", type=Path, default=Path.cwd())
    return finish(GATE, "ontology governance", check(repo_root(parser.parse_args(argv).root)))


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
