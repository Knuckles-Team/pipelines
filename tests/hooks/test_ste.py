@pytest.mark.parametrize(
    ("prose", "fires"),
    [
        ("The gate fetches the lock. The tool retrieves the source.", True),
        ("The gate fetches the lock. The tool fetches the source.", False),
    ],
)
def test_cluster_fires_only_when_both_terms_appear(
    repo: Repo, capsys: pytest.CaptureFixture[str], prose: str, fires: bool
) -> None:
    repo.commit({"README.md": f"# fixture\n\n{prose}\n"})
    assert repo.run("ste-census") == (1 if fires else 0)
    out = capsys.readouterr().out
    if fires:
        assert "cluster terms fetch and retrieve both present; pick one term" in out
    else:
        assert "OK: no findings" in out


