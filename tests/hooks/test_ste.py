def test_abbreviations_do_not_end_sentences() -> None:
    protect = frozenset({"e.g."})
    assert len(sentence_spans("Use e.g. this. End.", protect)) == 2
    assert len(sentence_spans("Use e.g. this. End.", frozenset())) == 3


def test_abbreviation_protect_needs_a_word_boundary() -> None:
    protect = frozenset({"Ms."})
    assert len(sentence_spans("The gate audits stale claims. The run ends.", protect)) == 2
