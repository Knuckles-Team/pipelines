@pytest.mark.spec("PIPE-VALIDATION-R002")
def test_catalog_name_remains_strict(repo: Repo, ambient_catalog: Path) -> None:
    ambient_catalog.write_text(json.dumps({"version": "1", "identities": [NAME]}))
