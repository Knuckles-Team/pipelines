"""Git display names are contextual; independent identity sources stay strict."""
from __future__ import annotations

import json
from pathlib import Path

import pytest

from pipelines_hooks.privacy import classify, identities
from tests.hooks.conftest import Repo, set_local_identity

NAME = "Asterloom"


@pytest.fixture
def ambient_catalog(repo: Repo, tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> Path:
    monkeypatch.delenv("AGENT_UTILITIES_PRIVACY_IDENTIFIERS", raising=False)
    set_local_identity(repo.root, name=NAME, email="writer@sample.invalid")
    catalog = tmp_path / "policy.json"
    catalog.write_text(json.dumps({"version": "1", "identities": ["catalogpersontoken"]}))
    return catalog


@pytest.mark.spec("PIPE-VALIDATION-R002")
def test_git_name_product_passes_but_attribution_fails(repo: Repo, ambient_catalog: Path) -> None:
    repo.commit({"docs/product.md": "Asterloom CLI integration.\n", "pkg/tool.py": "PRODUCT = 'Asterloom'\n"})
    assert repo.run("tracked-privacy", "--identity-catalog", str(ambient_catalog)) == 0
    repo.commit({"docs/product.md": "Written by Asterloom.\n"})
    assert repo.run("tracked-privacy", "--identity-catalog", str(ambient_catalog)) == 1


@pytest.mark.spec("PIPE-VALIDATION-R002")
@pytest.mark.parametrize("line", [
    "Author: Asterloom", 'OWNER = "Asterloom"', '{"author_name": "Asterloom"}',
    'git config user.name "Asterloom"', 'git config --local user.name "Asterloom"',
    "Generated by ASTERLOOM", "Asterloom (maintainer)", 'user.name = "Asterloom"',
])
def test_attribution_contexts_remain_sensitive(line: str) -> None:
    names = frozenset({NAME.casefold()})
    assert classify.classify_line(line, identifiers=frozenset(), display_names=names, deployment_doc=False)
    assert classify.classify_runtime_source_line(line, identifiers=frozenset(), display_names=names)


@pytest.mark.spec("PIPE-VALIDATION-R002")
@pytest.mark.parametrize("source", ["account", "hostname", "home", "email", "override"])
def test_independent_sources_override_display_name_context(repo: Repo, ambient_catalog: Path, monkeypatch: pytest.MonkeyPatch, source: str) -> None:
    if source == "account":
        monkeypatch.setattr(identities.getpass, "getuser", lambda: NAME)
    elif source == "hostname":
        monkeypatch.setattr(identities.socket, "gethostname", lambda: NAME)
    elif source == "home":
        monkeypatch.setattr(Path, "home", classmethod(lambda cls: Path("/home") / NAME))
    elif source == "email":
        set_local_identity(repo.root, name=NAME, email=NAME)
    else:
        monkeypatch.setenv("AGENT_UTILITIES_PRIVACY_IDENTIFIERS", NAME)
    candidates = identities.derive_identity_candidates(repo.root)
    assert NAME.casefold() in candidates.strict
    assert NAME.casefold() not in candidates.display_names
    repo.commit({"docs/product.md": "Asterloom CLI integration.\n"})
    assert repo.run("tracked-privacy", "--identity-catalog", str(ambient_catalog)) == 1


