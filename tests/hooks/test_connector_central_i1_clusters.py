TEST_USING = (
    "from demo_mcp.connector_sources import CONNECTOR, declaration\n\n\n"
    "def test_x():\n    assert declaration().connector == CONNECTOR\n"
)


def _repo(
    tmp_path: Path, sources: str, *, tests: dict[str, str] | None = None, pkg_files: dict[str, str] | None = None
) -> Path:
    root = tmp_path / "demo-mcp"
    pkg = root / "demo_mcp"
    (pkg / "skills").mkdir(parents=True)
    (root / "tests").mkdir()
    (root / "pyproject.toml").write_text(PYPROJECT, encoding="utf-8")
    (pkg / "__init__.py").write_text("", encoding="utf-8")
    (pkg / "connector_sources.py").write_text(sources, encoding="utf-8")
    for rel, text in (tests or {}).items():
        (root / "tests" / rel).write_text(text, encoding="utf-8")
    for rel, text in (pkg_files or {}).items():
        (pkg / rel).write_text(text, encoding="utf-8")
    return root


def _run(root: Path, *ids: str) -> base.Ctx:
    ctx = base.make_ctx(root, {})
    assert ctx is not None
    for rid in ids:
        base.RULES[rid](ctx)
    return ctx


def _text(root: Path, rel: str) -> str:
    return (root / rel).read_text(encoding="utf-8")


def _notes(ctx: base.Ctx, rid: str) -> list[dict]:
    return [i for i in ctx.review.items if i["step"] == rid]


