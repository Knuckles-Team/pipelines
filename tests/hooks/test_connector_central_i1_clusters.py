MULTI_VERSION = '__author__ = "a"\n__credits__ = "b"\n__version__ = "3.3.5"\n'
MULTI_INIT = (
    "from demo_mcp.version import __author__, __credits__, __version__\n\n"
    '__all__ = ["__version__", "__author__", "__credits__"]\n'
)


@pytest.mark.spec("PIPE-GATES-R016.58")
def test_k1_import_of_version_with_author_and_credits(tmp_path: Path) -> None:
    root = _repo(
        tmp_path,
        "",
        pkg_files={
            "version.py": MULTI_VERSION,
            "__init__.py": MULTI_INIT,
            "tool.py": "from demo_mcp.version import __author__, __version__\n\nBANNER = (__author__, __version__)\n",
        },
    )
    ctx = _run(root, "w1.k1")
    assert not _notes(ctx, "w1.k1")
    assert "__version__" not in _text(root, "demo_mcp/version.py") and "__author__" in _text(
        root, "demo_mcp/version.py"
    )
    for rel in ("demo_mcp/__init__.py", "demo_mcp/tool.py"):
        out = _text(root, rel)
        assert "import version as _v" in out and '__version__ = _v("demo-mcp")' in out
        assert "demo_mcp.version import __author__" in out and "__version__," not in out
        ast.parse(out)
    # the assignment follows every import so no later import lands below code
    tool = _text(root, "demo_mcp/tool.py")
    assert tool.index("import version") < tool.index("__version__ = _v")


